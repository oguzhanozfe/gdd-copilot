"""CLI: python -m gdd_copilot {fetch,generate,check,bench} ..."""
from __future__ import annotations

import argparse
import json
import os
import time
from pathlib import Path

from . import bench, check, corpus, render

STEAM = Path("corpus/steam")


def _load_pitch(path: str) -> dict:
    p = json.loads(Path(path).read_text())
    p["chunks"] = corpus.load(STEAM, p["refs"], [Path(n) for n in p.get("notes", [])])
    return p


def _write_outputs(out: Path, raw: str, p: dict) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    results = check.check_markdown(raw, p["chunks"])
    summary = check.summarize(results)
    (out / "gdd.raw.md").write_text(raw + "\n")
    (out / "gdd.md").write_text(render.to_markdown(raw, p["chunks"]))
    (out / "gdd.html").write_text(render.to_html(raw, p["chunks"], results, p["title"]))
    (out / "check.md").write_text(check.report_markdown(results, f"Citation check: {p['title']}"))
    (out / "check.json").write_text(json.dumps(
        {"summary": summary, "results": [r.__dict__ for r in results]}, indent=2, ensure_ascii=False) + "\n")
    return summary


def _ollama_digest(model: str) -> str:
    import urllib.request
    host = os.environ.get("OLLAMA_HOST", "http://127.0.0.1:11434").rstrip("/")
    try:
        with urllib.request.urlopen(host + "/api/tags", timeout=10) as r:
            tags = json.load(r)["models"]
        return "digest " + next(m["digest"][:12] for m in tags if m["name"] == model)
    except Exception:
        return "(digest unknown)"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gdd_copilot")
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fetch", help="snapshot Steam data for app ids")
    f.add_argument("appids", nargs="+", type=int)
    g = sub.add_parser("generate", help="generate + check a GDD from a pitch JSON")
    g.add_argument("pitch")
    g.add_argument("--out", required=True)
    c = sub.add_parser("check", help="re-check an existing gdd.raw.md and re-render outputs")
    c.add_argument("pitch")
    c.add_argument("--out", required=True)
    b = sub.add_parser("bench", help="planted-claim benchmark against a generated GDD")
    b.add_argument("gdd", nargs="+")
    b.add_argument("--json")
    a = ap.parse_args(argv)

    if a.cmd == "fetch":
        from . import fetch
        for path in fetch.save(a.appids, STEAM):
            print("wrote", path)
    elif a.cmd == "generate":
        from .generate import USAGE, call_llm, generate, provider, with_retry
        p = _load_pitch(a.pitch)
        t0 = time.time()
        raw = generate(p["title"], p["pitch"], p["chunks"], with_retry(call_llm),
                       cache=Path(a.out) / ".cache")
        name, model = provider()
        extra = _ollama_digest(model) if name == "ollama" else (
            f"{USAGE['calls']} calls, {USAGE['prompt_tokens']} prompt + {USAGE['completion_tokens']} completion tokens")
        raw += (f"\n<!-- generated by gdd-copilot with {name}/{model} ({extra}) "
                f"on {time.strftime('%Y-%m-%d')} in {time.time() - t0:.0f}s -->")
        print(json.dumps(_write_outputs(Path(a.out), raw, p), indent=2))
    elif a.cmd == "check":
        p = _load_pitch(a.pitch)
        raw = (Path(a.out) / "gdd.raw.md").read_text().rstrip("\n")
        print(json.dumps(_write_outputs(Path(a.out), raw, p), indent=2))
    elif a.cmd == "bench":
        chunks = corpus.load(STEAM)
        snaps = bench.load_snaps(STEAM)
        report = {gp: bench.run(Path(gp).read_text(), chunks, snaps) for gp in a.gdd}
        for gp, r in report.items():
            print(gp, {k: v for k, v in r.items() if k != "rows"})
        if a.json:
            Path(a.json).write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
