"""CLI: python -m gdd_copilot {fetch,generate,check,bench} ..."""
from __future__ import annotations

import argparse
import json
import os
import time
from pathlib import Path

from . import bench, check, corpus, render

STEAM = Path("corpus/steam")
RECORDED = Path("examples/ollama-qwen3.5-9b")  # committed GDDs + recorded/ model responses for replay


def _load_pitch(path: str) -> dict:
    p = json.loads(Path(path).read_text())
    p["chunks"] = corpus.load(STEAM, p["refs"], [Path(n) for n in p.get("notes", [])])
    return p


def _write_outputs(out: Path, raw: str, p: dict) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    results = check.check_markdown(raw, p["chunks"])
    summary = check.summarize(results)
    (out / "gdd.raw.md").write_text(raw + "\n")
    (out / "gdd.md").write_text(render.to_markdown(raw, p["chunks"]))
    (out / "gdd.html").write_text(render.to_html(raw, p["chunks"], results, p["title"]))
    (out / "check.md").write_text(check.report_markdown(results, f"Citation check: {p['title']}"))
    (out / "check.json").write_text(json.dumps(
        {"summary": summary, "results": [r.__dict__ for r in results]}, indent=2, ensure_ascii=False) + "\n")
    return summary


def _demo(out: Path) -> None:
    """Build every pitch with the best available model (cloud key, local Ollama, else replay)."""
    import html
    import re
    from .generate import call_llm, generate, provider, replay, resolve_mode
    mode = resolve_mode()
    if mode != "replay":
        os.environ["GDD_PROVIDER"] = mode
    rows = []
    for pf in sorted(Path("pitches").glob("*.json")):
        p = _load_pitch(str(pf))
        rec = RECORDED / pf.stem
        footer = re.search(r"<!--.*?-->", (rec / "gdd.raw.md").read_text(), re.S).group(0)
        recorded = re.search(r"with (\S+) .*? on (\S+)", footer)
        recorded = f"{recorded.group(1)}, {recorded.group(2)}" if recorded else "unknown model"
        fallback = replay(rec / "recorded")
        used = {"replay": 0, "live": 0}

        def llm(system, user):
            if mode != "replay":
                try:
                    out_text = call_llm(system, user)
                    used["live"] += 1
                    return out_text
                except Exception as e:  # quota, timeout, no balance: keep the demo running
                    print(f"  live call failed ({type(e).__name__}: {e}); replaying this section")
            used["replay"] += 1
            return fallback(system, user)

        label = f"replay (recorded {recorded})" if mode == "replay" else "{}/{}".format(*provider())
        print(f"{pf.stem}: mode: {label}")
        raw = generate(p["title"], p["pitch"], p["chunks"], llm)
        if not used["live"]:  # identical to the committed example, so keep its provenance line
            raw += "\n" + footer
        else:
            raw += (f"\n<!-- generated by gdd-copilot demo with {label} ({used['live']} live, "
                    f"{used['replay']} replayed sections) on {time.strftime('%Y-%m-%d')} -->")
        s = _write_outputs(out / pf.stem, raw, p)
        print(f"  {s['supported']}/{s['claims']} claims with valid citations -> {out / pf.stem / 'gdd.html'}")
        rows.append(f'<tr><td><a href="{pf.stem}/gdd.html">{html.escape(p["title"])}</a></td>'
                    f'<td>{s["claims"]}</td><td>{s["supported"]} ({s["valid_citation_share"]:.0%})</td>'
                    f'<td>{s["proposals"]}</td><td>{s["questions"]}</td>'
                    f'<td>{"replay: " + html.escape(recorded) if not used["live"] else html.escape(label)}</td></tr>')
    (out / "index.html").write_text(INDEX.format(rows="\n".join(rows)))


